-- ============================================================
-- MIGRATION 9: EXAM CONTROL OPERATIONS
-- PART 1: ADMIN PAUSE / RESUME
-- ============================================================
--
-- Provides controlled administrative operations for pausing
-- and resuming an active examination session.
--
-- The database remains the authority for exam state and timing.
-- Students cannot directly change these fields.
-- ============================================================


-- ============================================================
-- 1. PAUSE EXAM SESSION
-- ============================================================
--
-- Authorized:
--   admin
--   superadmin
--
-- A session may only be paused when it is currently active.
--
-- The pause timestamp is generated by PostgreSQL.
-- The student's device cannot manipulate it.
-- ============================================================

create or replace function public.pause_exam_session(
    p_exam_session_id uuid,
    p_reason text default null
)
returns table (
    exam_session_id uuid,
    session_status text,
    paused_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_role text;
    v_session public.exam_sessions%rowtype;
    v_now timestamptz;
begin

    -- --------------------------------------------------------
    -- AUTHENTICATION
    -- --------------------------------------------------------

    if auth.uid() is null then
        raise exception 'Authentication required';
    end if;


    -- --------------------------------------------------------
    -- AUTHORIZATION
    -- --------------------------------------------------------

    v_role := public.current_user_role();

    if v_role not in ('admin', 'superadmin') then
        raise exception 'Administrative authorization required';
    end if;


    -- --------------------------------------------------------
    -- LOCK SESSION
    -- --------------------------------------------------------

    select *
    into v_session
    from public.exam_sessions
    where id = p_exam_session_id
    for update;


    if not found then
        raise exception 'Exam session does not exist';
    end if;


    -- --------------------------------------------------------
    -- VALIDATE STATE
    -- --------------------------------------------------------

    if v_session.status <> 'active' then
        raise exception
            'Only an active examination session can be paused';
    end if;


    -- --------------------------------------------------------
    -- AUTHORITATIVE TIMESTAMP
    -- --------------------------------------------------------

    v_now := now();


    -- --------------------------------------------------------
    -- PAUSE
    -- --------------------------------------------------------

    update public.exam_sessions
    set
        status = 'paused',
        paused_at = v_now,
        updated_at = v_now
    where id = p_exam_session_id
    returning *
    into v_session;


    -- --------------------------------------------------------
    -- AUDIT EVENT
    -- --------------------------------------------------------

    insert into public.exam_session_events (
        exam_session_id,
        event_type,
        event_data,
        performed_by
    )
    values (
        p_exam_session_id,
        'SESSION_PAUSED',
        jsonb_build_object(
            'reason', p_reason,
            'paused_at', v_now
        ),
        auth.uid()
    );


    -- --------------------------------------------------------
    -- RETURN
    -- --------------------------------------------------------

    return query
    select
        v_session.id,
        v_session.status,
        v_session.paused_at;

end;
$$;


-- ============================================================
-- 2. RESUME EXAM SESSION
-- ============================================================
--
-- Authorized:
--   admin
--   superadmin
--
-- The database calculates the exact pause duration.
--
-- total_paused_seconds is incremented using PostgreSQL time,
-- not the student's device clock.
-- ============================================================

create or replace function public.resume_exam_session(
    p_exam_session_id uuid,
    p_reason text default null
)
returns table (
    exam_session_id uuid,
    session_status text,
    total_paused_seconds integer,
    resumed_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_role text;
    v_session public.exam_sessions%rowtype;
    v_now timestamptz;
    v_pause_seconds integer;
begin

    -- --------------------------------------------------------
    -- AUTHENTICATION
    -- --------------------------------------------------------

    if auth.uid() is null then
        raise exception 'Authentication required';
    end if;


    -- --------------------------------------------------------
    -- AUTHORIZATION
    -- --------------------------------------------------------

    v_role := public.current_user_role();

    if v_role not in ('admin', 'superadmin') then
        raise exception 'Administrative authorization required';
    end if;


    -- --------------------------------------------------------
    -- LOCK SESSION
    -- --------------------------------------------------------

    select *
    into v_session
    from public.exam_sessions
    where id = p_exam_session_id
    for update;


    if not found then
        raise exception 'Exam session does not exist';
    end if;


    -- --------------------------------------------------------
    -- VALIDATE STATE
    -- --------------------------------------------------------

    if v_session.status <> 'paused' then
        raise exception
            'Only a paused examination session can be resumed';
    end if;


    if v_session.paused_at is null then
        raise exception
            'Paused session has no pause timestamp';
    end if;


    -- --------------------------------------------------------
    -- AUTHORITATIVE TIME
    -- --------------------------------------------------------

    v_now := now();


    v_pause_seconds :=
        greatest(
            0,
            floor(
                extract(
                    epoch from (v_now - v_session.paused_at)
                )
            )::integer
        );


    -- --------------------------------------------------------
    -- RESUME
    -- --------------------------------------------------------

    update public.exam_sessions
    set
        status = 'active',
        paused_at = null,
        total_paused_seconds =
            coalesce(total_paused_seconds, 0)
            + v_pause_seconds,
        updated_at = v_now
    where id = p_exam_session_id
    returning *
    into v_session;


    -- --------------------------------------------------------
    -- AUDIT EVENT
    -- --------------------------------------------------------

    insert into public.exam_session_events (
        exam_session_id,
        event_type,
        event_data,
        performed_by
    )
    values (
        p_exam_session_id,
        'SESSION_RESUMED',
        jsonb_build_object(
            'reason', p_reason,
            'resumed_at', v_now,
            'pause_duration_seconds', v_pause_seconds
        ),
        auth.uid()
    );


    -- --------------------------------------------------------
    -- RETURN
    -- --------------------------------------------------------

    return query
    select
        v_session.id,
        v_session.status,
        v_session.total_paused_seconds,
        v_now;

end;
$$;


-- ============================================================
-- 3. FUNCTION COMMENTS
-- ============================================================

comment on function public.pause_exam_session(uuid, text) is
    'Allows an authorized Admin or Superadmin to pause an active examination session using server-authoritative time.';

comment on function public.resume_exam_session(uuid, text) is
    'Allows an authorized Admin or Superadmin to resume a paused examination session and accurately account for paused time.';


-- ============================================================
-- 4. FUNCTION PRIVILEGES
-- ============================================================

revoke all on function public.pause_exam_session(uuid, text)
from public;

revoke all on function public.resume_exam_session(uuid, text)
from public;


grant execute on function public.pause_exam_session(uuid, text)
to authenticated;

grant execute on function public.resume_exam_session(uuid, text)
to authenticated;